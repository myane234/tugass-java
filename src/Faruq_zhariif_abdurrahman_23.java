public class Faruq_zhariif_abdurrahman_23 {
    // clear code
    public static void main(String[] args) {
        boolean hasil;

        // apakah 5 sama dengan 6 (hasilnya false)
        hasil = 5 == 6;
        System.out.println(hasil);

        // apakah 5 tidak sama dengan 6 (hasilnya true)
        hasil = 5 != 6;
        System.out.println(hasil);

        // apakah 5 lebih kecil dari 6 (hasilnya true)
        hasil = 5 < 6;
        System.out.println(hasil);

        // apakah 5 lebih besar dari 6 (hasilnya false)
        hasil = 5 > 6;
        System.out.println(hasil);

        // apakah 5 lebih kecil atau sama dengan 6 (hasilnya true)
        hasil = 5 <= 6;
        System.out.println(hasil);

        // cek apakah 5 lebih besar atau sama dengan 6 (hasilnya false)
        hasil = 5 >= 6;
        System.out.println(hasil);
    }
}