public class Faruq_zhariif_22 {
// clear code
    public static void main(String[] args) {
        int angka = 10; // nilai awal
        System.out.println(angka);

        angka += 5; // Penambahan nilai
        System.out.println(angka);

        angka -= 3; // Pengurangan nilai
        System.out.println(angka);

        int bilangan = 7;
        bilangan /= 3; // Pembagian bilangan
        System.out.println(bilangan);

        int bagi;
        bagi = 7 % 3; // Sisa pembagian
        System.out.println(bagi);
    }
}